    private void btnCargarDiccionarioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarDiccionarioActionPerformed

    javax.swing.JFileChooser buscador = new javax.swing.JFileChooser();
    int respuesta = buscador.showOpenDialog(this);
    if (respuesta == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File archivoElegido = buscador.getSelectedFile();
        String mensaje = gestor.cargarDiccionario(archivoElegido, diccionario);
        analizador = new Analizador(grafo, diccionario);
        txtConsola.setText(mensaje + "\n");
    }
    }//GEN-LAST:event_btnCargarDiccionarioActionPerformed

