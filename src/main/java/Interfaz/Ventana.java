    private void btnDijkstraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDijkstraActionPerformed

    String origen = txtOrigen.getText().trim();
    String destino = txtDestino.getText().trim();
    String neuro = txtNeuro.getText().trim();
    if(origen.isEmpty() || destino.isEmpty() || neuro.isEmpty()){
        txtConsola.setText(txtConsola.getText() + "Error: Ingresa Origen, Destino y Neurotransmisor.\n");
        return; 
    }
    String resultado = analizador.rutaDijkstra(origen, destino, neuro);
    txtConsola.setText(txtConsola.getText() + "\n--- RESULTADO DIJKSTRA ---\n" + resultado + "\n");
    }//GEN-LAST:event_btnDijkstraActionPerformed

    private void btnBFSActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBFSActionPerformed
        String origen = txtOrigen.getText().trim();
    
    if(origen.isEmpty()){
        txtConsola.setText(txtConsola.getText() + "Error: Ingresa la neurona de Origen para el BFS.\n");
        return;
    }
    String resultado = analizador.BFS(origen);
    txtConsola.setText(txtConsola.getText() + "\n--- ALCANCE BFS ---\n" + resultado + "\n");
    }//GEN-LAST:event_btnBFSActionPerformed

